// setTimeout() executa uma função após um intervalo de tempo especificado (em milissegundos).

// O primeiro parâmetro é uma arrow function que irá conter o código a ser executado e após o bloco de código encontramos a virgula com o segundo parâmetro que é o tempo em milissegundos.
setTimeout(() => {
    console.log("Esta mensagem é exibida após 1 segundo.");
}, 1000); // 1000 milissegundos = 1 segundo